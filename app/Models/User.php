<?php

namespace App\Models;

use App\Enums\UserStatus;
use App\Support\Phone;
use Database\Factories\UserFactory;
use Illuminate\Database\Eloquent\Casts\Attribute;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Relations\BelongsToMany;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Foundation\Auth\User as Authenticatable;
use Illuminate\Notifications\Notifiable;
use Illuminate\Support\Str;
use Laravel\Sanctum\HasApiTokens;
use Spatie\Permission\Traits\HasRoles;

class User extends Authenticatable
{
    /** @use HasFactory<UserFactory> */
    use HasApiTokens, HasFactory, HasRoles, Notifiable;

    /**
     * The attributes that are mass assignable.
     *
     * @var list<string>
     */
    protected $fillable = [
        'name',
        'email',
        'password',
        'status',
        'phone',
        'last_login_at',
        'must_change_password',
        'password_changed_at',
    ];

    /**
     * The attributes that should be hidden for serialization.
     *
     * @var list<string>
     */
    protected $hidden = [
        'password',
        'remember_token',
    ];

    /**
     * Get the attributes that should be cast.
     *
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'email_verified_at' => 'datetime',
            'password' => 'hashed',
            'status' => UserStatus::class,
            'last_login_at' => 'datetime',
            'must_change_password' => 'boolean',
            'password_changed_at' => 'datetime',
        ];
    }

    /**
     * Nomor HP selalu disimpan ternormalisasi (62xxxxxxxxxx).
     */
    protected function phone(): Attribute
    {
        return Attribute::make(set: fn (?string $value) => Phone::normalize($value));
    }

    /**
     * Email disimpan huruf kecil; string kosong menjadi NULL (akun tanpa email).
     */
    protected function email(): Attribute
    {
        return Attribute::make(set: fn (?string $value) => filled($value) ? Str::lower(trim($value)) : null);
    }

    /**
     * Kredensial untuk Auth::attempt() dari input login (email atau nomor HP).
     *
     * @return array<string, string|null>
     */
    public static function credentialsFor(string $login, string $password): array
    {
        $login = trim($login);

        return Phone::looksLikePhone($login)
            ? ['phone' => Phone::normalize($login), 'password' => $password]
            : ['email' => Str::lower($login), 'password' => $password];
    }

    /**
     * Tandai password sebagai sementara: user wajib menggantinya saat login.
     */
    public function requirePasswordChange(): void
    {
        $this->forceFill(['must_change_password' => true])->save();
    }

    /**
     * Audit logs generated by this user.
     */
    public function auditLogs(): HasMany
    {
        return $this->hasMany(AuditLog::class);
    }

    /**
     * Profil penghuni yang diwakili akun ini (FR-RES-005).
     *
     * @return BelongsToMany<Resident, $this>
     */
    public function residents(): BelongsToMany
    {
        return $this->belongsToMany(Resident::class, 'resident_user_accounts')
            ->using(ResidentUserAccount::class)
            ->withPivot('id', 'created_by')
            ->withTimestamps();
    }

    /**
     * Determine if the user account is active.
     */
    public function isActive(): bool
    {
        return $this->status === UserStatus::Active;
    }

    /**
     * Catat waktu login berhasil (web maupun API).
     */
    public function markLoggedIn(): void
    {
        $this->forceFill(['last_login_at' => now()])->saveQuietly();
    }

    /**
     * Nama route halaman pertama yang boleh dibuka user ini.
     *
     * Ditentukan dari izin yang dimiliki, bukan dari nama role, supaya role baru
     * yang dibuat lewat layar Role Management tidak diarahkan ke halaman yang
     * justru ditolak 403. Tambahkan pasangan `izin => route` di sini saat
     * menambah modul yang punya halaman utama sendiri.
     *
     * Dipakai LoginController (tujuan setelah login) dan halaman error
     * (tombol kembali), jadi keduanya tidak bisa saling bertentangan.
     */
    public function landingRoute(): string
    {
        $candidates = [
            'access-dashboard' => 'dashboard',
        ];

        foreach ($candidates as $permission => $route) {
            if ($this->can($permission)) {
                return $route;
            }
        }

        // Tidak ada satu pun halaman yang boleh dibuka — biarkan mendarat di
        // dashboard dan menerima 403 yang jujur, daripada berputar redirect.
        return 'dashboard';
    }
}
